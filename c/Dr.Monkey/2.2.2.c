// 2.2 常见 if 语句用法
#include <stdio.h>

int main()
{
    int a;
    printf("输入年份：\n");
    scanf("%d", &a);
    // a = 999;
    // a = 2000;
    // a = 1984;
    if ( (a%100!=0 && a%4==0) || a%400==0 ) {
        printf("%d年是闰年\n", a);
    } else {
        printf("%d年不是闰年", a);
    }
    // > 输入年份：
    // < 1111
    // > 1111年不是闰年
    // > 输入年份：
    // < 2000
    // > 2000年是闰年
    // > 输入年份：
    // < 1984
    // > 1984年是闰年
    return 0;
}