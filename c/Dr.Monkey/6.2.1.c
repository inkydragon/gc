// 6.2 指针与一维数组
#include <stdio.h>

int main()
{
    int a[5], *p;
    p = &a[0];
    printf("请输入5个数字：\n");
    for (int i=0; i<=4; i++) {
        printf("  请输入第%d个数字：", i+1);
        scanf("%d", p+i);
        *(p+i) = *(p+i)*2;
    }
    printf("加倍后的整数为："); 
    for (int i=0; i<=4; i++) printf("%d, ", *(p+i));
    // 请输入5个数字：
    //   请输入第1个数字：1
    //   请输入第2个数字：2
    //   请输入第3个数字：3
    //   请输入第4个数字：4
    //   请输入第5个数字：5
    // 加倍后的整数为：2, 4, 6, 8, 10,
    return 0;
}