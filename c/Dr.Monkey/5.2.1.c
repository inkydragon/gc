// 5.2 调用无参函数
#include <stdio.h>

void a() { printf("3.1415926\n"); }
void b() { printf("我能吞下玻璃而不伤身体\n"); }
void c() { printf("2.7182818\n"); }

int main()
{
    a();
    b(); c();
    b(); c();
    b();
    // 3.1415926
    // 我能吞下玻璃而不伤身体
    // 2.7182818
    // 我能吞下玻璃而不伤身体
    // 2.7182818
    // 我能吞下玻璃而不伤身体
    return 0;
}