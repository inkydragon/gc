// 1.tips 小知识点
#include <stdio.h>

int main()
{
    // %m.nf 
    double a,b,c;
    a = 1.23;
    b = 4.56;
    c = 7.89;

    printf( "---------0123456789\n");
    printf("a=%%5.2f =(%5.2f)\n", a);
    printf("b=%%-5.2f=(%-5.2f)\n", b);
    printf("c=%%7.4f =(%7.4f)\n", c);
    printf( "---------0123456789\n");
    // ---------0123456789
    // a=%5.2f =( 1.23)
    // b=%-5.2f=(4.56 )
    // c=%7.4f =( 7.8900)
    // ---------0123456789
    return 0;
}